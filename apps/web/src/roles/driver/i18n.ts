const DICTS: Record<Lang, Dict> = { en, si, ta };

export type T = (k: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICTS[lang] ?? en;
  return (k, vars) => {
    let s = d[k] ?? en[k] ?? k;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, x) => (vars[x] !== undefined ? String(vars[x]) : m));
    return s;
  };
}

export const I18n = createContext<{ lang: Lang; t: T }>({ lang: "en", t: makeT("en") });
export const useT = () => useContext(I18n);
